import { useEffect, useState, type ReactNode } from 'react';
import { View, Text } from 'react-native';
import { useTranslation } from 'react-i18next';
import { useAppConfigStore } from '@/stores/appConfigStore';
import { colors, spacing, radius } from '@/theme/index';
import { fonts } from '@/theme/typography';

/**
 * A SURFACE is anything the backend code may switch off (server config/mobile_ui.php →
 * `ui.hidden`): a tab, a card, a button, a row, a whole screen. Wrap it:
 *
 *   <Surface id="teacher.home.rose_card">…</Surface>
 *   <Surface id="screen.teacher.collect" screen>…</Surface>   // a screen: shows a notice instead
 *
 * Ids are dotted, lower-case, stable: `<role>.<screen>.<element>`, `tab.<role>.<name>`,
 * `screen.<role>.<name>`. The full list lives in docs/MOBILE_SURFACES.md (generated by
 * scripts/list-surfaces.py). Default is ON: an unknown id, an old manifest, no network —
 * everything shows. Reads the cached config, so it holds offline.
 */
export function isSurfaceOn(id: string): boolean {
  const hidden = useAppConfigStore.getState().config.ui?.hidden;
  return !hidden || !hidden.includes(id);
}

/** Reactive: re-renders when the manifest changes. */
export function useSurface(id: string): boolean {
  return useAppConfigStore((s) => !(s.config.ui?.hidden ?? []).includes(id));
}

/** The whole hidden set, for a list that must drop entries (a tab bar). */
export function useHiddenSurfaces(): ReadonlySet<string> {
  const hidden = useAppConfigStore((s) => s.config.ui?.hidden);
  return new Set(hidden ?? []);
}

/** The notice a hidden SCREEN shows (server `ui.notices[id]`, else the generic line). */
export function useSurfaceNotice(id: string): string {
  const { t } = useTranslation();
  const notice = useAppConfigStore((s) => s.config.ui?.notices?.[id]);
  return notice || t('misc_ui.surface_off');
}

export function Surface({ id, screen, fallback, children }: { id: string; screen?: boolean; fallback?: ReactNode; children: ReactNode }) {
  const on = useSurface(id);
  const ready = useFirstFrame(!!screen);
  if (on) return ready ? <>{children}</> : <View style={{ flex: 1, backgroundColor: colors.background }} />;
  if (fallback !== undefined) return <>{fallback}</>;
  return screen ? <HiddenScreenNotice id={id} /> : null;
}

/**
 * A screen root renders a blank page the first time and its content on the next frame
 * (founder 2026-10-11: «a slight delay on every tap, on every device»). The native push
 * cannot start until the screen's first render has committed, so a page with a few
 * hundred elements held the tap for the time its whole tree took; now the page slides in
 * at once and fills a frame later, under the animation. Off for non-screen surfaces.
 */
function useFirstFrame(deferred: boolean): boolean {
  const [ready, setReady] = useState(!deferred);
  useEffect(() => {
    if (ready) return;
    const h = requestAnimationFrame(() => setReady(true));
    return () => cancelAnimationFrame(h);
  }, [ready]);
  return ready;
}

/** What a switched-off screen shows: the backend's own words for it, centred, nothing else. */
export function HiddenScreenNotice({ id }: { id: string }) {
  const notice = useSurfaceNotice(id);
  return (
    <View style={{ flex: 1, backgroundColor: colors.background, alignItems: 'center', justifyContent: 'center', padding: spacing.xl }}>
      <View style={{ backgroundColor: colors.surface, borderRadius: radius.xl, borderWidth: 1, borderColor: colors.border, padding: spacing.xl, maxWidth: 360 }}>
        <Text style={{ fontFamily: fonts.medium, fontSize: 15, lineHeight: 24, color: colors.textPrimary, textAlign: 'center' }}>{notice}</Text>
      </View>
    </View>
  );
}
