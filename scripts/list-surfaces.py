#!/usr/bin/env python3
"""Write docs/MOBILE_SURFACES.md: every <Surface id="…"> and tab id the app declares, grouped,
so whoever edits the server's config/mobile_ui.php knows what can be switched off."""
import os, re, glob
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ids = {}
for f in glob.glob(os.path.join(ROOT, 'app/**/*.tsx'), recursive=True) + glob.glob(os.path.join(ROOT, 'src/**/*.tsx'), recursive=True):
    if '__tests__' in f: continue
    src = open(f, encoding='utf-8').read()
    for m in re.finditer(r'<Surface\s+id="([a-z0-9_.:-]+)"([^>]*)>', src):
        ids.setdefault(m.group(1), []).append((os.path.relpath(f, ROOT), 'screen' if ' screen' in m.group(2) else 'element'))
    for m in re.finditer(r"surfaceId\(['\"]([a-z0-9_.:-]+)['\"]\)|TAB_SURFACE\s*=\s*['\"]([a-z0-9_.:-]+)['\"]", src):
        ids.setdefault(m.group(1) or m.group(2), []).append((os.path.relpath(f, ROOT), 'tab'))
    for m in re.finditer(r"const TAB_ORDER = \[([^\]]+)\]", src):
        role = re.search(r'app/\((\w+)\)/', f)
        if role:
            for name in re.findall(r"'([a-z-]+)'", m.group(1)):
                ids.setdefault(f'tab.{role.group(1)}.{name}', []).append((os.path.relpath(f, ROOT), 'tab'))
slots = {}
for f in glob.glob(os.path.join(ROOT, 'app/**/*.tsx'), recursive=True) + glob.glob(os.path.join(ROOT, 'src/**/*.tsx'), recursive=True):
    if '__tests__' in f or f.endswith('src/ui/Slot.tsx'): continue  # the component's own doc-comment examples
    src = open(f, encoding='utf-8').read()
    for m in re.finditer(r'<Slot\s+id="([a-z0-9_.:-]+)"([^>]*)/?>', src):
        ctx = re.search(r'ctx=\{\{\s*([^}]*)\}\}', m.group(2))
        slots.setdefault(m.group(1), set()).add((os.path.relpath(f, ROOT), ctx.group(1).strip() if ctx else ''))
sl = ['# Mobile slots', '', 'Generated by `scripts/list-surfaces.py`. A slot is a place a screen leaves OPEN for UI the',
      'server\'s `config/mobile_ui.php` → `slots` adds: a notice, a card with up to 3 buttons, or a button.',
      'Nothing shows until backend code puts a block there. `ctx` = the names a block\'s `when` may read',
      'besides role / online / platform / is_assistant / can.<ability>.', '']
for sid, where in sorted(slots.items()):
    ctxs = sorted({c for _, c in where if c})
    sl.append(f'- `{sid}` — ' + ', '.join(sorted({w for w, _ in where})) + (f' · ctx: `{", ".join(ctxs)}`' if ctxs else ''))
open(os.path.join(ROOT, 'docs/MOBILE_SLOTS.md'), 'w', encoding='utf-8').write('\n'.join(sl) + '\n')
print(f'{len(slots)} slots → docs/MOBILE_SLOTS.md')

groups = {}
for sid, where in sorted(ids.items()):
    groups.setdefault(sid.split('.')[0], []).append((sid, where))
out = ['# Mobile surfaces', '', 'Generated by `scripts/list-surfaces.py`. Every id here can be switched off from the server\'s',
       '`config/mobile_ui.php` → `hidden`. A `screen.*` id hides a whole screen (it shows the notice from', '`notices`); a `tab.*` id removes a tab; the rest hide one element. Default: everything on.', '']
for g, rows in groups.items():
    out.append(f'## {g}'); out.append('')
    for sid, where in rows:
        kinds = sorted({k for _, k in where})
        out.append(f'- `{sid}` — {"/".join(kinds)} · ' + ', '.join(sorted({w for w, _ in where})))
    out.append('')
os.makedirs(os.path.join(ROOT, 'docs'), exist_ok=True)
open(os.path.join(ROOT, 'docs/MOBILE_SURFACES.md'), 'w', encoding='utf-8').write('\n'.join(out))
print(f'{len(ids)} surfaces → docs/MOBILE_SURFACES.md')
